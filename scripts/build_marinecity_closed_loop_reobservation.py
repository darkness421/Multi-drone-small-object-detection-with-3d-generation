    loop_after = [float(row["after_closed_loop_ambiguity"]) for row in rows]

    x = list(range(len(rows)))
    fig, ax = plt.subplots(figsize=(11, 4.8), dpi=180)
    ax.bar([i - 0.24 for i in x], before, width=0.22, label="Before A(o)", color="#2563eb")
    ax.bar(x, raw_after, width=0.22, label="After raw A(o)", color="#94a3b8")
    ax.bar([i + 0.24 for i in x], loop_after, width=0.22, label="After closed-loop A(o)", color="#16a34a")
    ax.axhline(0.75, color="#f97316", linestyle="--", linewidth=1.2, label="reobserve threshold")
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=35, ha="right")
    ax.set_ylim(0.0, 1.05)
    ax.set_ylabel("ambiguity score")
    ax.set_title("Closed-loop targeted re-observation reduces routed hypothesis ambiguity")
    ax.grid(axis="y", color="#e2e8f0")
    ax.legend(ncol=2, fontsize=8)
    fig.tight_layout()
    fig.savefig(fig_dir / "closed_loop_ambiguity_before_after.png", facecolor="white")
    plt.close(fig)

    before_counts = Counter(row["before_action"] for row in rows)
    after_counts = Counter(row["after_action"] for row in rows)
    actions = ["finalize", "monitor", "reject", "targeted_reobserve"]
    fig, ax = plt.subplots(figsize=(7.8, 4.4), dpi=180)
    width = 0.36
    ax.bar([i - width / 2 for i in range(len(actions))], [before_counts.get(a, 0) for a in actions], width=width, label="Before", color="#2563eb")
