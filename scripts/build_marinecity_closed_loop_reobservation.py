def find_reobserve_candidate(
    hypothesis: dict[str, Any],
    reobserve_tokens: list[EvidenceToken],
    projections: dict[str, dict[str, Any]],
    *,
    max_distance: float,
    min_confidence: float,
) -> tuple[EvidenceToken | None, float | None, list[dict[str, Any]]]:
    scenario = hypothesis["scenario_short"]
    cls = hypothesis["class_name"]
    missing = set(hypothesis.get("missing_uav_ids", []))
    center = hypothesis["center_scene_units"]
    candidates: list[tuple[float, EvidenceToken]] = []
    considered: list[dict[str, Any]] = []
    for token in reobserve_tokens:
        if float(token.confidence) < min_confidence:
            continue
        token_hypothesis = str(token.metadata.get("hypothesis_id") or "")
        token_scenario = str(token.metadata.get("scenario_short") or short_scenario(scenario_id(token)))
        if token_hypothesis and token_hypothesis != hypothesis["hypothesis_id"]:
            continue
        if token_hypothesis and token_hypothesis == hypothesis["hypothesis_id"]:
            if class_name(token) == cls and token.uav_id in missing:
                dist = distance_xy(projections[token.token_id]["association_point"], center)
                candidates.append((dist, token))
                considered.append(
                    {
                        "token_id": token.token_id,
                        "uav_id": token.uav_id,
                        "class_name": class_name(token),
                        "confidence": float(token.confidence),
                        "uncertainty": float(token.uncertainty),
                        "distance_xy": dist,
                        "match_reason": "hypothesis_id",
                    }
                )
            continue
        if short_scenario(scenario_id(token)) != scenario:
            if token_scenario != scenario:
                continue
        if token_scenario != scenario:
            continue
        if class_name(token) != cls:
            continue
        if token.uav_id not in missing:
            continue
        dist = distance_xy(projections[token.token_id]["association_point"], center)
        candidates.append((dist, token))
        considered.append(
            {
                "token_id": token.token_id,
                "uav_id": token.uav_id,
                "class_name": class_name(token),
                "confidence": float(token.confidence),
                "uncertainty": float(token.uncertainty),
                "distance_xy": dist,
            }
        )
    candidates.sort(key=lambda item: item[0])
    if not candidates:
        return None, None, considered
    distance, token = candidates[0]
    if distance > max_distance:
        return None, distance, considered
    return token, distance, considered


def after_state(
    hypothesis: dict[str, Any],
    token: EvidenceToken | None,
    *,
    support_gain: float,
    confidence_gain_weight: float,
    max_confidence_gain: float,
) -> dict[str, Any]:
    before_views = set(hypothesis.get("uav_ids", []))
    before_action = hypothesis["recommended_action"]
    before_ambiguity = float(hypothesis["ambiguity_score"])
    before_conf = float(hypothesis.get("mean_confidence", 0.0))
    before_unc = float(hypothesis.get("mean_uncertainty", before_ambiguity))
    before_tokens = int(hypothesis.get("token_count", 1))

    if token is None:
        return {
            "after_view_count": int(hypothesis["view_count"]),
            "after_uav_ids": sorted(before_views),
            "after_token_count": before_tokens,
            "after_mean_confidence": before_conf,
            "after_mean_uncertainty": before_unc,
            "after_raw_ambiguity": before_ambiguity,
            "after_closed_loop_ambiguity": before_ambiguity,
            "after_action": before_action,
            "support_gain_applied": 0.0,
            "confidence_gain_applied": 0.0,
            "resolved": False,
            "resolution_status": "unresolved_no_matching_reobservation_token",
        }

    after_views = set(before_views)
    after_views.add(token.uav_id)
    after_tokens = before_tokens + 1
    token_conf = float(token.confidence)
    token_unc = float(token.uncertainty)
    after_conf = (before_conf * before_tokens + token_conf) / after_tokens
    after_unc = (before_unc * before_tokens + token_unc) / after_tokens

    # Raw recomputation keeps the detector uncertainty dominant. The closed-loop
    # score additionally removes the missing-evidence surcharge once the
    # requested UAV returns a same-class token, which is the actual closed-loop
    # contract under review.
    raw = clamp(after_unc)
    conf_gain = min(max_confidence_gain, max(0.0, token_conf - before_conf) * confidence_gain_weight)
    closed_loop = clamp(raw - support_gain - conf_gain)
    action = route_action(
        view_count=len(after_views),
        ambiguity=closed_loop,
        mean_confidence=after_conf,
        projection_valid_ratio=1.0,
    )
    resolved = before_action == "targeted_reobserve" and action != "targeted_reobserve"
    status = "resolved_to_" + action if resolved else "unresolved_still_ambiguous"
    return {
        "after_view_count": len(after_views),
        "after_uav_ids": sorted(after_views),
        "after_token_count": after_tokens,
        "after_mean_confidence": after_conf,
        "after_mean_uncertainty": after_unc,
        "after_raw_ambiguity": raw,
        "after_closed_loop_ambiguity": closed_loop,
        "after_action": action,
        "support_gain_applied": support_gain,
        "confidence_gain_applied": conf_gain,
        "resolved": resolved,
        "resolution_status": status,
    }


def font(size: int, bold: bool = False) -> ImageFont.ImageFont:
    names = ["DejaVuSans-Bold.ttf", "DejaVuSans.ttf"] if bold else ["DejaVuSans.ttf"]
    for name in names:
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    return ImageFont.load_default()


FONT_TITLE = font(34, True)
FONT_H = font(22, True)
FONT_BODY = font(17)
FONT_SMALL = font(14)


def fit_image(path: Path | None, size: tuple[int, int]) -> Image.Image:
    if not path or not path.exists():
        canvas = Image.new("RGB", size, "#f8fafc")
        draw = ImageDraw.Draw(canvas)
        draw.rectangle([0, 0, size[0] - 1, size[1] - 1], outline="#cbd5e1", width=2)
        draw.text((18, size[1] // 2 - 10), "missing image", fill="#b91c1c", font=FONT_SMALL)
        return canvas
    image = Image.open(path).convert("RGB")
    image.thumbnail(size, Image.Resampling.LANCZOS)
    canvas = Image.new("RGB", size, "#ffffff")
    canvas.paste(image, ((size[0] - image.width) // 2, (size[1] - image.height) // 2))
    return canvas


def token_image_with_box(token: EvidenceToken | None, size: tuple[int, int]) -> Image.Image:
    if token is None:
        return fit_image(None, size)
    image_path = Path(str(token.metadata.get("image_path", "")))
    if not image_path.exists():
        return fit_image(None, size)
    image = Image.open(image_path).convert("RGB")
    original = image.size
    image.thumbnail(size, Image.Resampling.LANCZOS)
    scale_x = image.width / max(1, original[0])
    scale_y = image.height / max(1, original[1])
    canvas = Image.new("RGB", size, "#ffffff")
    x0 = (size[0] - image.width) // 2
    y0 = (size[1] - image.height) // 2
    canvas.paste(image, (x0, y0))
    draw = ImageDraw.Draw(canvas)
    bx, by, bw, bh = [float(v) for v in token.bbox_2d[:4]]
    box = [
        x0 + bx * scale_x,
        y0 + by * scale_y,
        x0 + (bx + bw) * scale_x,
        y0 + (by + bh) * scale_y,
    ]
    draw.rectangle(box, outline="#ef4444", width=4)
    draw.text((box[0], max(0, box[1] - 22)), f"{class_name(token)} {float(token.confidence):.2f}", fill="#ef4444", font=FONT_SMALL)
    return canvas


def crop_for_token(token: EvidenceToken | None) -> Path | None:
    if token is None:
        return None
    crop = token.metadata.get("crop_path")
    if crop:
        path = Path(str(crop))
        if not path.is_absolute():
            path = ROOT / path
        return path
    return None


def wrap(draw: ImageDraw.ImageDraw, text: str, xy: tuple[int, int], width: int, line_height: int, fill: str = "#0f172a") -> int:
    x, y = xy
    for para in text.splitlines():
        for line in textwrap.wrap(para, width=width) or [""]:
            draw.text((x, y), line, fill=fill, font=FONT_BODY)
            y += line_height
    return y


def draw_card(draw: ImageDraw.ImageDraw, box: tuple[int, int, int, int], title: str, body: str, accent: str) -> None:
    draw.rounded_rectangle(box, radius=8, fill="#ffffff", outline=accent, width=3)
    x0, y0, x1, _ = box
    draw.rectangle([x0, y0, x1, y0 + 40], fill=accent)
    draw.text((x0 + 14, y0 + 8), title, fill="white", font=FONT_H)
    wrap(draw, body, (x0 + 14, y0 + 58), 48, 24)


def build_panel(row: dict[str, Any], base_token: EvidenceToken | None, reobs_token: EvidenceToken | None, out_path: Path) -> None:
    canvas = Image.new("RGB", (1800, 1120), "#f8fafc")
    draw = ImageDraw.Draw(canvas)
    draw.rectangle([0, 0, 1800, 82], fill="#0f172a")
    title = f"Closed-loop re-observation: {row['hypothesis_id']} ({row['scenario_short']}, {row['class_name']})"
    draw.text((32, 22), title, fill="white", font=FONT_TITLE)

    before_img = token_image_with_box(base_token, (520, 300))
    reobs_img = token_image_with_box(reobs_token, (520, 300))
    before_crop = fit_image(crop_for_token(base_token), (260, 220))
    reobs_crop = fit_image(crop_for_token(reobs_token), (260, 220))

    canvas.paste(before_img, (40, 130))
    canvas.paste(reobs_img, (640, 130))
    canvas.paste(before_crop, (1240, 130))
    canvas.paste(reobs_crop, (1510, 130))
    draw.text((40, 102), "Before supporting view", fill="#1d4ed8", font=FONT_H)
    draw.text((640, 102), "Targeted re-observation view", fill="#b45309", font=FONT_H)
    draw.text((1240, 102), "Before crop", fill="#1d4ed8", font=FONT_H)
    draw.text((1510, 102), "Reobserve crop", fill="#b45309", font=FONT_H)

    before = (
        f"Views: {row['before_uav_ids']} ({row['before_view_count']})\n"
        f"Tokens: {row['before_token_count']}\n"
        f"Mean confidence: {float(row['before_mean_confidence']):.3f}\n"
        f"A(o): {float(row['before_ambiguity']):.3f}\n"
        f"Action: {row['before_action']}"
    )
    target = (
        f"Requested missing UAV(s): {row['missing_uav_ids']}\n"
        f"Selected UAV: {row.get('reobserve_uav_id') or 'none'}\n"
        f"Token: {row.get('reobserve_token_id') or 'no matching token'}\n"
        f"Confidence: {float(row.get('reobserve_confidence') or 0.0):.3f}\n"
        f"Match distance: {row.get('reobserve_match_distance', '-')}"
    )
    after = (
        f"Views: {row['after_uav_ids']} ({row['after_view_count']})\n"
        f"Raw A(o): {float(row['after_raw_ambiguity']):.3f}\n"
        f"Closed-loop A(o): {float(row['after_closed_loop_ambiguity']):.3f}\n"
        f"Action: {row['after_action']}\n"
        f"Outcome: {row['resolution_status']}"
    )
    draw_card(draw, (40, 500, 580, 830), "Before Graph State", before, "#2563eb")
    draw_card(draw, (630, 500, 1170, 830), "Targeted Evidence", target, "#f97316")
    draw_card(draw, (1220, 500, 1760, 830), "After Graph Update", after, "#16a34a" if row["resolved"] else "#64748b")
    note = (
        "Protocol: the before state is the 78-token viewer160 evidence graph. "
        "The re-observation token is selected from real-Cesium evidence in the missing UAV "
        "direction. When source metadata is targeted_reobservation, camera poses were "
        "commanded from the graph plan; this is still camera-pose closed-loop validation, "
        "not autonomous physical flight."
    )
    wrap(draw, note, (44, 880), 145, 26, fill="#334155")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    canvas.save(out_path)


def build_contact_sheet(panel_paths: list[Path], out_path: Path) -> None:
    cols = 3
    thumb = (520, 324)
    rows = math.ceil(len(panel_paths) / cols)
    canvas = Image.new("RGB", (cols * 560 + 80, rows * 380 + 120), "#f8fafc")
    draw = ImageDraw.Draw(canvas)
    draw.rectangle([0, 0, canvas.width, 80], fill="#0f172a")
    draw.text((30, 22), "MarineCity Closed-loop Re-observation Panels", fill="white", font=FONT_TITLE)
    for idx, path in enumerate(panel_paths):
        x = 40 + (idx % cols) * 560
        y = 110 + (idx // cols) * 380
        draw.rounded_rectangle([x, y, x + 530, y + 350], radius=8, fill="#ffffff", outline="#cbd5e1", width=2)
        image = fit_image(path, thumb)
        canvas.paste(image, (x + 5, y + 8))
        draw.text((x + 14, y + 330), path.stem, fill="#334155", font=FONT_SMALL)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    canvas.save(out_path)


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    fields = [
        "hypothesis_id",
        "scenario_short",
        "class_name",
        "before_view_count",
        "before_uav_ids",
        "missing_uav_ids",
        "before_token_count",
        "before_mean_confidence",
        "before_ambiguity",
        "before_action",
        "reobserve_uav_id",
        "reobserve_token_id",
        "reobserve_confidence",
        "reobserve_uncertainty",
        "reobserve_match_distance",
        "after_view_count",
        "after_uav_ids",
        "after_token_count",
        "after_mean_confidence",
        "after_raw_ambiguity",
        "after_closed_loop_ambiguity",
        "after_action",
        "resolved",
        "resolution_status",
        "panel_path",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow({field: row.get(field, "") for field in fields})


