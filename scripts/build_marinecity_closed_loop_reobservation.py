def read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")


def clamp(value: float, low: float = 0.0, high: float = 1.0) -> float:
    return max(low, min(high, value))


def token_key(token: EvidenceToken) -> str:
    return f"{short_scenario(scenario_id(token))}:{token.uav_id}:{class_name(token)}:{token.token_id}"


def load_base_tokens(graph_dir: Path) -> dict[str, EvidenceToken]:
    summary = read_json(graph_dir / "summary.json")
    token_path = Path(summary["source_tokens"])
    tokens = load_tokens_jsonl(token_path)
    return {token.token_id: token for token in tokens}


