def build_rows(args: argparse.Namespace) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    hypotheses = read_json(args.base_graph / "hypotheses.json")
    base_tokens = load_base_tokens(args.base_graph)
    reobs_tokens = load_tokens_jsonl(args.reobserve_tokens)
    fresh_commanded = any(
        str(token.metadata.get("source", "")).endswith("targeted_reobservation")
        or "targeted_reobservation" in str(token.metadata.get("image_path", ""))
        for token in reobs_tokens
    )
    if fresh_commanded:
        evidence_protocol = "fresh_commanded_isaac_cesium_targeted_reobservation"
        evidence_protocol_label = "fresh commanded Isaac/Cesium targeted camera-pose recapture"
        claim_boundary = (
            "Fresh camera poses are generated from the graph target plan and recaptured in Isaac/Cesium; "
            "this supports closed-loop camera-pose/evidence-update validation, not autonomous physical drone flight."
        )
    else:
        evidence_protocol = "saved_real_cesium_session_recapture_replay"
        evidence_protocol_label = "saved real-Cesium session-recapture detector tokens"
        claim_boundary = (
            "Closed-loop replay using saved real-Cesium recapture tokens; "
            "do not claim fully autonomous physical re-observation from this artifact alone."
        )
    reobs_projections = {token.token_id: token_projection(token, args.hfov_deg, args.ground_z) for token in reobs_tokens}

    rows: list[dict[str, Any]] = []
    panel_paths: list[Path] = []
    for hypothesis in hypotheses:
        if hypothesis.get("recommended_action") != "targeted_reobserve":
            continue
        token, match_distance, considered = find_reobserve_candidate(
            hypothesis,
            reobs_tokens,
            reobs_projections,
            max_distance=args.max_match_distance,
            min_confidence=args.min_reobserve_confidence,
        )
        after = after_state(
            hypothesis,
            token,
            support_gain=args.support_gain,
            confidence_gain_weight=args.confidence_gain_weight,
            max_confidence_gain=args.max_confidence_gain,
        )
        base_token = base_tokens.get((hypothesis.get("token_ids") or [""])[0])
        panel_path = args.out_dir / "panels" / f"{hypothesis['hypothesis_id']}_closed_loop.png"
        row = {
            "hypothesis_id": hypothesis["hypothesis_id"],
            "scenario_short": hypothesis["scenario_short"],
            "class_name": hypothesis["class_name"],
            "before_view_count": int(hypothesis["view_count"]),
            "before_uav_ids": ",".join(hypothesis.get("uav_ids", [])),
            "missing_uav_ids": ",".join(hypothesis.get("missing_uav_ids", [])),
            "before_token_count": int(hypothesis.get("token_count", 0)),
            "before_mean_confidence": float(hypothesis.get("mean_confidence", 0.0)),
            "before_ambiguity": float(hypothesis.get("ambiguity_score", 0.0)),
            "before_action": hypothesis.get("recommended_action", ""),
            "reobserve_uav_id": token.uav_id if token else "",
            "reobserve_token_id": token.token_id if token else "",
            "reobserve_confidence": float(token.confidence) if token else "",
            "reobserve_uncertainty": float(token.uncertainty) if token else "",
            "reobserve_match_distance": f"{match_distance:.2f}" if match_distance is not None else "",
            "candidate_count": len(considered),
            "candidate_tokens": considered,
            "panel_path": str(panel_path),
            **after,
        }
        row["after_uav_ids"] = ",".join(row["after_uav_ids"])
        build_panel(row, base_token, token, panel_path)
        panel_paths.append(panel_path)
        rows.append(row)

    summary = {
        "status": "closed_loop_reobservation_update_complete",
        "evidence_protocol": evidence_protocol,
        "evidence_protocol_label": evidence_protocol_label,
        "base_graph": str(args.base_graph),
        "reobserve_tokens": str(args.reobserve_tokens),
        "output_dir": str(args.out_dir),
        "routed_hypotheses": len(rows),
        "matched_reobservation_tokens": sum(1 for row in rows if row.get("reobserve_token_id")),
        "resolved_hypotheses": sum(1 for row in rows if row["resolved"]),
        "mean_before_ambiguity": sum(float(row["before_ambiguity"]) for row in rows) / max(1, len(rows)),
        "mean_after_raw_ambiguity": sum(float(row["after_raw_ambiguity"]) for row in rows) / max(1, len(rows)),
        "mean_after_closed_loop_ambiguity": sum(float(row["after_closed_loop_ambiguity"]) for row in rows) / max(1, len(rows)),
        "before_action_counts": dict(Counter(row["before_action"] for row in rows)),
        "after_action_counts": dict(Counter(row["after_action"] for row in rows)),
        "support_gain": args.support_gain,
        "confidence_gain_weight": args.confidence_gain_weight,
        "max_confidence_gain": args.max_confidence_gain,
        "max_match_distance": args.max_match_distance,
        "min_reobserve_confidence": args.min_reobserve_confidence,
        "claim_boundary": claim_boundary,
        "panel_count": len(panel_paths),
        "contact_sheet": str(args.out_dir / "closed_loop_contact_sheet.png"),
    }
    build_contact_sheet(panel_paths, args.out_dir / "closed_loop_contact_sheet.png")
    return rows, summary


def main() -> None:
    parser = argparse.ArgumentParser(description="Build MarineCity closed-loop re-observation update artifacts.")
    parser.add_argument("--base-graph", type=Path, default=DEFAULT_BASE_GRAPH)
    parser.add_argument("--reobserve-tokens", type=Path, default=DEFAULT_REOBS_TOKENS)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--hfov-deg", type=float, default=60.0)
    parser.add_argument("--ground-z", type=float, default=0.0)
    parser.add_argument("--max-match-distance", type=float, default=180.0)
    parser.add_argument("--min-reobserve-confidence", type=float, default=0.0)
    parser.add_argument("--support-gain", type=float, default=0.18)
    parser.add_argument("--confidence-gain-weight", type=float, default=0.08)
    parser.add_argument("--max-confidence-gain", type=float, default=0.04)
    args = parser.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)
    rows, summary = build_rows(args)
    write_csv(args.out_dir / "closed_loop_reobservation_results.csv", rows)
    write_json(args.out_dir / "closed_loop_reobservation_summary.json", summary)
    write_json(args.out_dir / "closed_loop_reobservation_rows.json", rows)
    build_figures(args.out_dir, rows, summary)
    write_markdown(args.out_dir, rows, summary)
    print(json.dumps(summary, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
