"""Build the MarineCity neural-3D completion result table.

The table is pending-safe: if no verified metric rows exist, it writes a clear
pending row instead of allowing placeholder metrics to look paper-ready.
"""

from __future__ import annotations

import csv
import json
from datetime import datetime
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
COMPARISON = ROOT / "outputs/experiments/3d_generation_comparison.csv"
OUT_TEX = ROOT / "paper/tables/marinecity_3d_completion_results_table.tex"
OUT_MD = ROOT / "outputs/reports/live/marinecity_3d_completion_results_table.md"
QUALITY_METRICS = ["PSNR", "SSIM", "LPIPS"]


def read_csv(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        return []
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return [{str(k): str(v) for k, v in row.items()} for row in csv.DictReader(handle)]


def numeric(value: Any) -> float | None:
    if value in (None, ""):
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def verified_rows(rows: list[dict[str, str]]) -> list[dict[str, str]]:
    verified = []
    for row in rows:
        status = (row.get("status", "") or "").lower()
        if status in {"", "pending", "placeholder", "missing", "dry_run", "mock"}:
            continue
        if not all(numeric(row.get(metric)) is not None for metric in QUALITY_METRICS):
            continue
        verified.append(row)
    return sorted(verified, key=lambda row: numeric(row.get("PSNR")) or -1.0, reverse=True)


def fmt(value: Any, digits: int = 3) -> str:
    number = numeric(value)
    if number is None:
        return "--"
    return f"{number:.{digits}f}"


def latex_escape(value: Any) -> str:
    text = str(value or "")
    return (
        text.replace("\\", r"\textbackslash{}")
        .replace("&", r"\&")
        .replace("%", r"\%")
        .replace("_", r"\_")
        .replace("#", r"\#")
    )


def write_tex(rows: list[dict[str, str]]) -> None:
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "% Auto-generated by scripts/build_marinecity_3d_results_table.py",
        "% Pending-safe: placeholder/dry-run rows are intentionally excluded.",
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        r"Method & PSNR$\uparrow$ & SSIM$\uparrow$ & LPIPS$\downarrow$ & FPS$\uparrow$ & Time (min)$\downarrow$ \\",
        r"\midrule",
    ]
    if rows:
        for row in rows:
            lines.append(
                f"{latex_escape(row.get('display_name') or row.get('method'))} & "
                f"{fmt(row.get('PSNR'), 2)} & {fmt(row.get('SSIM'), 3)} & {fmt(row.get('LPIPS'), 3)} & "
                f"{fmt(row.get('FPS'), 2)} & {fmt(row.get('train_time_min'), 1)} \\\\"
            )
    else:
        lines.append(
            r"\multicolumn{6}{c}{Pending verified neural-3D metric rows; "
            r"real-Cesium captures and transforms are ready.} \\"
        )
    lines.extend([r"\bottomrule", r"\end{tabular}", ""])
    OUT_TEX.write_text("\n".join(lines), encoding="utf-8")


def write_md(all_rows: list[dict[str, str]], rows: list[dict[str, str]]) -> None:
    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# MarineCity Neural-3D Completion Result Table",
        "",
        f"Updated: `{datetime.now().strftime('%Y-%m-%d %H:%M:%S KST')}`",
        f"Source CSV: `{COMPARISON.relative_to(ROOT)}`",
        f"Verified rows: `{len(rows)}` / total rows `{len(all_rows)}`",
        "",
        "Rows are admitted only when status is non-placeholder and PSNR, SSIM, and LPIPS are numeric.",
        "",
    ]
    if rows:
        lines.extend(["| Method | PSNR | SSIM | LPIPS | FPS | Time min | Status |", "| --- | ---: | ---: | ---: | ---: | ---: | --- |"])
        for row in rows:
            lines.append(
                f"| {row.get('display_name') or row.get('method')} | {fmt(row.get('PSNR'), 2)} | "
                f"{fmt(row.get('SSIM'), 3)} | {fmt(row.get('LPIPS'), 3)} | "
                f"{fmt(row.get('FPS'), 2)} | {fmt(row.get('train_time_min'), 1)} | {row.get('status')} |"
            )
    else:
        lines.append("- No verified neural-3D metric rows yet.")
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    all_rows = read_csv(COMPARISON)
    rows = verified_rows(all_rows)
    write_tex(rows)
    write_md(all_rows, rows)
    print(json.dumps({"tex": str(OUT_TEX.relative_to(ROOT)), "markdown": str(OUT_MD.relative_to(ROOT)), "verified_rows": len(rows)}, indent=2))


if __name__ == "__main__":
    main()
